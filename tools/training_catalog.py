"""Derive Web scene roster and compact type chart directly from the C definitions."""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parents[1]
def generate(root=ROOT):
 source=(root/'core/training.c').read_text()
 scenes=[]
 for name,search,low,high,pool,grass,light in re.findall(r'\{"([^"]+)","([^"]+)",(\d+),(\d+),\{([\d,]+)\},(0x[\da-f]+),(0x[\da-f]+)\}',source):
  scenes.append(dict(name=name,search=search,minLevel=int(low),maxLevel=int(high),pool=list(map(int,pool.split(','))),grass=int(grass,16),light=int(light,16)))
 assert len(scenes)==6
 events=json.loads((ROOT/'assets/training-events.json').read_text())
 assert len(events['ambient'])==6 and all(len(row)==6 for row in events['ambient'])
 header='/* Generated by tools/training_catalog.py. */\nstatic const char *const training_events[6][6]={\n'
 header+='\n'.join('{'+','.join(json.dumps(v,ensure_ascii=False) for v in row)+'},' for row in events['ambient'])+'\n};\n'
 header+='static const char *const training_care_events[4]={'+','.join(json.dumps(v,ensure_ascii=False) for v in events['care'])+'};\n'
 (root/'core/training_events.h').write_text(header)
 code=(ROOT/'core/game.c').read_text().split('unsigned pp_gym_effectiveness')[1].split('} else if(!enemy)')[0]
 chart={}
 for move,conditions in re.findall(r'(?:if|else if)\(move==PP_(\w+)\) \{(.*?)(?=\} else if|\Z)',code,re.S):
  row={}
  for types,factor in re.findall(r'if\((.*?)\)factor=(\d+);',conditions):
   for target in re.findall(r'type==PP_(\w+)',types):row[target]=int(factor)
  chart[move]=row
 assert len(chart)==18
 out='// Generated from core/training.c and core/game.c; run tools/training_catalog.py.\n'
 out+='export const trainingScenes='+json.dumps(scenes,ensure_ascii=False,separators=(',',':'))+';\n'
 out+='export const trainingAmbientEvents='+json.dumps(events['ambient'],ensure_ascii=False,separators=(',',':'))+';\n'
 out+='export const trainingCareEvents='+json.dumps(events['care'],ensure_ascii=False,separators=(',',':'))+';\n'
 out+='export const trainingTypeChart='+json.dumps(chart,separators=(',',':'))+';\n'
 (root/'web/training-catalog.mjs').write_text(out)
if __name__=='__main__':generate()

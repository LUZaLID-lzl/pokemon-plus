"""One bounded, allocation-free release effect for LVGL and Web."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
BODY=r'''
 if(time>=1000)return;
 int flight=time<300?time:300;
 int x=side?336-whole(flight*56,300):24+whole(flight*56,300);
 int arc=flight<150?whole(flight*14,150):whole((300-flight)*14,150);
 int y=136-arc;
 if(time<500){
  int gap=time<300?0:whole((time-300)*8,200);
  paint(data,x-6,y-8-gap,12,2,0x182a38,255);
  paint(data,x-8,y-6-gap,16,5,0x182a38,255);
  paint(data,x-6,y-6-gap,12,4,0xed7968,255);
  paint(data,x-6,y-2-gap,12,2,0x182a38,255);
  paint(data,x-8,y+1+gap,16,5,0x182a38,255);
  paint(data,x-6,y+1+gap,12,4,0xd5e0e5,255);
  paint(data,x-6,y+6+gap,12,2,0x182a38,255);
  if(time<360){paint(data,x-3,y-3,6,6,0x182a38,255);paint(data,x-1,y-1,2,2,0xffffff,255);}
 }
 if(time>=340&&time<600){
  int alpha=time<480?220:whole((600-time)*220,120);
  paint(data,x-3,108,6,28,0xe9f8ff,alpha);
 }
 if(time>=360&&time<900){
  int radius=8+whole((time-360)*30,540),alpha=220-whole((time-360)*220,540);
  for(int i=0;i<6;i++){
   int dx=i<4?(i%2?1:-1):0,dy=i<4?(i<2?-1:1):(i==4?-1:1);
   int px=x+dx*radius,py=120+dy*radius;
   paint(data,px-2,py,5,1,i%2?0xffedb3:0xc9f4ff,alpha);
   paint(data,px,py-2,1,5,i%2?0xffedb3:0xc9f4ff,alpha);
  }
 }
'''
STATE=r'''
 int opacity=time<360?0:time<720?whole((time-360)*255,360):255;
 int white=time<500?255:time<880?255-whole((time-500)*255,380):0;
 int drop=time<360?6:time<720?6-whole((time-360)*6,360):0;
'''
def generate(root=ROOT):
 c='''/* Generated by tools/battle_entrance.py. Coordinates relative to battle body. */
#pragma once
#define PP_BATTLE_ENTRANCE_MS 1000u
typedef void (*pp_entry_paint)(void *,int,int,int,int,unsigned,unsigned);
typedef struct {unsigned opacity,white;int drop;} pp_entry_state;
static inline int pp_entry_whole(int a,int b){return a/b;}
static inline pp_entry_state pp_battle_entry_state(unsigned time){
'''+STATE.replace('whole(','pp_entry_whole(')+'return (pp_entry_state){opacity,white,drop};\n}\n'
 c+='static inline void pp_battle_entry_paint(unsigned side,unsigned time,pp_entry_paint paint,void *data){\n'+BODY.replace('whole(','pp_entry_whole(')+'}\n'
 (root/'core/battle_entrance.h').write_text(c)
 js='// Generated by tools/battle_entrance.py. Coordinates relative to battle body.\nexport const battleEntryDuration=1000;\nconst whole=(a,b)=>Math.floor(a/b);\n'
 js+='export function battleEntryState(time){\n'+re.sub(r'\bint\b','let',STATE)+'return {opacity,white,drop};\n}\n'
 js+='export function battleEntryPaint(side,time,paint){const data=null;\n'+re.sub(r'\bint\b','let',BODY)+'}\n'
 (root/'web/battle-entrance.mjs').write_text(js)
if __name__=='__main__':generate()

"""Publish the reviewed balance configuration to firmware, browser and manifests."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
def load():return json.loads((ROOT/'assets/balance.json').read_text())
def generate():
 b=load();names=['树果','肥皂','药水','玩具','精力饼干','宠物蛋','孵化药剂','咕噜球','神树精华']
 items=[]
 for i,(name,price) in enumerate(zip(names,b['prices'])):
  effects=b['care'][i][:4] if i<5 else [0]*4
  items.append('{"%s",%s,%s}'%(name,price,','.join(map(str,effects))))
 header='#pragma once\n/* Generated by tools/balance_catalog.py; edit assets/balance.json. */\n#define PP_BALANCE_XP_TENTHS %s\n#define PP_BALANCE_SCENES {%s}\n#define PP_BALANCE_ITEMS %s\n'%(b['xpTenths'],','.join(map(str,b['sceneRequirements'])),','.join(items))
 header+='#define PP_BALANCE_NOVICE_SCALES {%s}\n'%','.join(map(str,b['training']['noviceScale']))
 header+='#define PP_TRAINING_XP_MULTIPLIER %su\n'%b['training']['xpMultiplier']
 header+='#define PP_TRAINING_SUPPLY_THRESHOLDS {%s}\n'%','.join(map(str,b['training']['autoSupplyThresholds']))
 header+='#define PP_SHOP_PRICE %su\n#define PP_SHOP_DURATION_MS %su\n#define PP_SHOP_GRID {%s}\n#define PP_SHOP_RING {%s}\n#define PP_SHOP_WEIGHTS {%s}\n#define PP_TRAINING_ITEM_WEIGHTS {%s}\n'%(b['shop']['drawPrice'],b['shop']['durationMs'],','.join(str(i if i is not None else 255) for i in b['shop']['grid']),','.join(map(str,b['shop']['ring'])),','.join(map(str,b['shop']['weights'])),','.join(map(str,b['training']['itemWeights'])))
 for key,macro in [('laps','LAPS'),('stepMs','STEP_MS'),('slowSteps','SLOW_STEPS'),('slowStepMs','SLOW_STEP_MS'),('blinkMs','BLINK_MS'),('blinkCount','BLINK_COUNT')]:
  header+='#define PP_SHOP_%s %su\n'%(macro,b['shop'][key])
 (ROOT/'core/balance_config.h').write_text(header)
 (ROOT/'web/balance-config.mjs').write_text('// Generated from assets/balance.json.\nexport const balance='+json.dumps(b,ensure_ascii=False,separators=(',',':'))+';\n')
def patch_manifest(m):
 b=load();m['balance']=b
 for scene,n in zip(m['scenes'],b['sceneRequirements']):scene.update(price=None,unlock={'type':'prosperity','requiredPets':n})
 for i,(item,price) in enumerate(zip(m['items'],b['prices'])):item.update(price=price,retired=i==b['shop']['retiredItem'])
 m['walking']=dict(b['walking'],icon='hud/steps.png',xpMode='level-relative')
 for key,g in m.get('gyms',{}).items():
  if isinstance(g,dict) and 'enemies' in g:
   level=sum(e['level'] for e in g['enemies'])//3;g.update(winXp=3*(1+3*level//10),lossXp=0,rematchCoins=20+5*['pewter','cerulean','vermilion','celadon','fuchsia','saffron','cinnabar','viridian'].index(key),xpMode='per-battle-plus-first-clear')
 if m.get('gyms',{}).get('pewter'):
  m['gyms'].update({k:m['gyms']['pewter'][k] for k in ['firstClearCoins','rematchCoins','winXp','lossXp']})
 if 'hospital' in m:m['hospital'].update(recovery='health-only',freeHealth=60,treatmentCoins=20)
if __name__=='__main__':
 generate()
 for p in [ROOT/'web/manifest.json',ROOT/'sdcard/pokemon-plus/manifest.json']:
  m=json.loads(p.read_text());patch_manifest(m);p.write_text(json.dumps(m,ensure_ascii=False,indent=2)+'\n')

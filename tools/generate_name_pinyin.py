"""Build the embedded naming lexicon. Dev dependency: pypinyin (MIT)."""
from pathlib import Path
import json
from collections import defaultdict
from pypinyin import pinyin, Style
root=Path(__file__).resolve().parents[1]
# Prioritize common nicknames; the remaining existing game glyphs are also available.
priority='小大球宝贝龙火水草雷电冰风雪云星月日光花叶木石海空山林梦心皮喵咪咕噜糖果豆米奶茶可乐布丁丸子团圆胖胖壮壮萌萌甜甜乖乖黑白红蓝绿黄紫金银橙粉彩虹闪闪亮亮点点天天晴晴悠悠安安宁宁乐乐欢欢喜喜飞飞毛毛绒绒泡泡多多朵朵巧巧奇奇琪琦莉琳霖灵玲铃零萌萌萌阳洋羊耀瑶遥睿瑞锐雨羽宇玉鱼星昕欣馨鑫新辰晨宸橘橙樱桃莓梨柚柠檬芒椰葡萄西瓜薄荷饼干糖糕巧克力奶酪蜂蜜团团圆圆'
chars=list(dict.fromkeys(priority+''.join(sorted(set((root/'assets/font-characters.txt').read_text())))))
lex=defaultdict(list)
for ch in chars:
 if not '\u4e00'<=ch<='\u9fff':continue
 for spelling in pinyin(ch,style=Style.NORMAL,heteronym=True)[0]:
  if spelling.isascii() and spelling.isalpha() and ch not in lex[spelling]:lex[spelling].append(ch)
rows=[(k,''.join(v)) for k,v in sorted(lex.items())]
header='/* Generated by tools/generate_name_pinyin.py; pypinyin pronunciation data (MIT). */\n#pragma once\n'
header+='static const struct { const char *key,*chars; } pp_pinyin[]={\n'
header+=''.join(' {"%s","%s"},\n'%row for row in rows)+'};\n#define PP_PINYIN_COUNT (sizeof(pp_pinyin)/sizeof(pp_pinyin[0]))\n'
(root/'main/name_pinyin.h').write_text(header)
(root/'web/name-pinyin.json').write_text(json.dumps(dict(rows),ensure_ascii=False))
print(len(rows),'syllables,',len(set(''.join(v for _,v in rows))),'Chinese characters')

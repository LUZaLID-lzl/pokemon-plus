def pixels(color,mark):
 rgb=int(color,16);out=[]
 for y in range(16):
  for x in range(16):
   d=(2*x-15)**2+(2*y-15)**2
   out.append(0 if d>225 else 0xff152c3c if d>173 else 0xfff6f0d8 if 3<=x<13 and 3<=y<13 and mark[y-3][x-3]=='#' else 0xff000000|rgb)
 return out


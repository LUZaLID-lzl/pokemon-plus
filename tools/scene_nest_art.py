"""Derive scene props and a shared egg anchor from the reviewed MobiIoT atlas."""
from pathlib import Path
from PIL import Image, ImageDraw
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]

def catalog(root=ROOT):
    return json.loads((root / 'assets/scene-nests.json').read_text())

def build_nest(scene, root=ROOT):
    config = catalog(root)
    sheet = Image.open(root / 'assets' / config['source']).convert('RGBA')
    col, row = scene % 4, scene // 4
    top, bottom = config['sourceRows'][row]
    cell = sheet.crop((col * sheet.width // 4, top,
                       (col + 1) * sheet.width // 4, bottom))
    cell.putalpha(cell.getchannel('A').point(lambda a: 255 if a >= 200 else 0))
    bounds = cell.getbbox()
    assert bounds, f'Missing nest {scene}'
    assert 0 < bounds[0] < bounds[2] < cell.width and 0 < bounds[1] < bounds[3] < cell.height, f'Clipped nest {scene}'
    cell = cell.crop(bounds)
    cell.thumbnail(tuple(config['nativeSize']), Image.Resampling.NEAREST)
    # Use the scenery's contrast curve on this placed prop as well. UI/pets
    # stay crisp, but a nest should share the floor's softer lighting.
    contrast = json.loads((root / 'assets/scene-display.json').read_text())['contrast']
    cell.putdata([tuple(round(128 + (c - 128) * contrast) for c in (r, g, b)) + (a,)
                  for r, g, b, a in cell.getdata()])
    # Quantize only opaque colors, retaining binary transparent pixels exactly.
    cell = cell.quantize(colors=15, method=Image.Quantize.FASTOCTREE).convert('RGBA')
    cell.putdata([(r, g, b, 255) if a >= 128 else (0, 0, 0, 0)
                  for r, g, b, a in cell.getdata()])
    native = Image.new('RGBA', tuple(config['nativeSize']))
    native.alpha_composite(cell, ((native.width - cell.width) // 2, native.height - cell.height))
    return native.resize(tuple(config['size']), Image.Resampling.NEAREST)

def front_rim(scene, root=ROOT):
    config = catalog(root)
    if config.get('embeddedSources'):
        from scene_art import scene_base
        image = scene_base(root, config['embeddedSources'][scene])
        x, y = config['scenes'][scene]['position']
        top = config['frontTop']
        front = image.crop((x,y+top,x+config['size'][0],y+config['size'][1])).convert('RGBA')
        mask = Image.new('L',(24,5))
        # The lower lip's RGB comes from the edited floor itself, so it
        # exactly matches the scene; only this shallow raised edge hides egg.
        ImageDraw.Draw(mask).polygon(config['frontMask'],fill=255)
        front.putalpha(mask.resize(front.size,Image.Resampling.NEAREST))
        return front
    nest = build_nest(scene, root)
    top = catalog(root)['frontTop']
    return nest.crop((0, top, nest.width, nest.height))

def decorate_scene(image, scene, root=ROOT):
    config = catalog(root)
    if config.get('embeddedSources'):
        return image.convert('RGB')
    out = image.convert('RGBA')
    out.alpha_composite(build_nest(scene, root), tuple(config['scenes'][scene]['position']))
    return out.convert('RGB')

def manifest_nests(root=ROOT):
    config = catalog(root)
    return {key: config[key] for key in ('version', 'size', 'eggOffset', 'frontTop')} | {
        'frontSize': [config['size'][0], config['size'][1] - config['frontTop']],
        'scenes': [dict(s, front=f'nest-fronts/{s["scene"]}.png') for s in config['scenes']]}

def write_header(root=ROOT):
    config = catalog(root)
    lines = ['#pragma once', '#include <stdint.h>', '/* Generated by tools/scene_nest_art.py from assets/scene-nests.json. */',
             f'#define PP_SCENE_NEST_COUNT {len(config["scenes"])}',
             f'#define PP_SCENE_NEST_FRONT_TOP {config["frontTop"]}',
             'static const int16_t pp_scene_nest_positions[PP_SCENE_NEST_COUNT][2]={']
    lines += ['  {%d,%d},' % tuple(s['position']) for s in config['scenes']]
    lines += ['};', 'static inline void pp_scene_egg_position(unsigned scene,int *x,int *y) {',
              '  if(scene>=PP_SCENE_NEST_COUNT)scene=0;',
              '  *x=pp_scene_nest_positions[scene][0]+%d;' % config['eggOffset'][0],
              '  *y=pp_scene_nest_positions[scene][1]+%d;' % config['eggOffset'][1], '}', '']
    (root / 'core/scene_nests.h').write_text('\n'.join(lines))
    (root / 'web/scene-nest-anchors.mjs').write_text(
        '// Generated from assets/scene-nests.json by tools/scene_nest_art.py.\n'
        + 'export const nestAnchors=' + json.dumps([s['position'] for s in config['scenes']]) + ';\n')

def export_nests(export, root=ROOT):
    write_header(root)
    for scene in range(len(catalog(root)['scenes'])):
        export(front_rim(scene, root), 'nest-fronts', str(scene), True, indexed=True)

def record_generation(root=ROOT):
    config = catalog(root)
    record = dict(service='MobiIoT', model='gpt-image-1.5', attempts=1,
                  source=config['source'], prompt=config['prompt'], reference=config['reference'],
                  sourceSha256=hashlib.sha256((root / 'assets' / config['source']).read_bytes()).hexdigest(),
                  recipe='4 columns, measured sourceRows, first13 props; alpha >=200; full unclipped prop nearest fit to24x14; scenery contrast curve;15 colors; integer3x; foreground bottom15px; muted local materials, raised woven rim, dark hollow and contact shadow',
                  revision=config['version'],
                  reviewed=True, sceneCount=13)
    if config.get('embeddedSources'):
        record['atlasRole']='Position reference only; runtime scenes use13 localized AI ground edits'
        record['terrainGeneration']=config.get('terrainDirectory','scene-nest-terrain')+'-generation.json'
        record['embeddedSources']=config['embeddedSources']
        record['recipe']='Original120px scene + localized40x32 native AI terrain edit;15 local colors;3 native perimeter blend;48 scene colors; shared contrast; integer3x; front RGB cut from actual edited background'
    (root / 'assets/scene-nests-generation.json').write_text(json.dumps(record, ensure_ascii=False, indent=2) + '\n')

if __name__ == '__main__':
    write_header()
    record_generation()

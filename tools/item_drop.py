"""Shared integer fall/bounce timing; no save changes or game RNG."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BODY='''
 int x=ground_x+(32-size)/2;
 int base=ground_y+32-size;
 int y=base;
 if(time<400)y=96+(base-96)*time*time/160000;
 else if(time<680){int t=time-400;y=base-4*12*t*(280-t)/78400;}
 int opacity=time<80?time*255/80:255;
'''
def generate(root=ROOT):
 c='''/* Generated by tools/item_drop.py. Screen coordinates, 400ms fall + one 280ms bounce. */
#pragma once
#define PP_ITEM_DROP_MS 680u
typedef struct {int x,y;unsigned opacity;} pp_item_drop_state;
static inline pp_item_drop_state pp_item_drop(unsigned age,int ground_x,int ground_y,int size){
 int time=age<680?age:680;
'''+BODY+'''return (pp_item_drop_state){x,y,(unsigned)opacity};
}
'''
 (root/'core/item_drop.h').write_text(c)
 # Explicit truncation at each division matches the native integer arithmetic.
 js='''// Generated by tools/item_drop.py. Screen coordinates.
export const itemDropDuration=680;
export function itemDrop(age,groundX,groundY,size=24){
 const time=Math.max(0,Math.min(680,Math.floor(age))),x=groundX+Math.trunc((32-size)/2),base=groundY+32-size;
 let y=base;
 if(time<400)y=96+Math.trunc((base-96)*time*time/160000);
 else if(time<680){const t=time-400;y=base-Math.trunc(4*12*t*(280-t)/78400)}
 return {x,y,opacity:time<80?Math.trunc(time*255/80):255};
}
'''
 (root/'web/item-drop.mjs').write_text(js)
if __name__=='__main__':generate()

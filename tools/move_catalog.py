"""One skill catalog for firmware and Web, independent of the playable roster."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
TYPES = dict(zip(
    ['电','草','火','水','一般','虫','毒','飞行','地面','岩石','妖精','超能','格斗','冰','钢','幽灵','恶','龙'],
    ['ELECTRIC','GRASS','FIRE','WATER','NORMAL','BUG','POISON','FLYING','GROUND','ROCK','FAIRY','PSYCHIC','FIGHTING','ICE','STEEL','GHOST','DARK','DRAGON']))
TYPES['超能力'] = 'PSYCHIC'

def load_catalog():
    data = json.loads((ROOT/'assets/moves.json').read_text())
    moves, families = data['moves'], data['families']
    assert [m['id'] for m in moves] == list(range(len(moves)))
    assert [f['species'] for f in families] == list(range(len(families)))
    assert len(moves) == 4*len(families)
    assert sorted(d for f in families for d in f['nationalIds']) == list(range(1,152))
    assert len({f['name'] for f in families}) == len(families)
    for f in families:
        assert sorted(m['slot'] for m in moves if m['species']==f['name']) == [0,1,2,3]
    for m in moves:
        assert m['type'] in TYPES and m['source'].startswith('https://')
    assert len(data['formStats'])==151
    assert [f['nationalId'] for f in data['formStats']]==list(range(1,152))
    for m in moves: assert isinstance(m['power'],int) and 0<=m['power']<=150
    for family in families:
        row=sorted([m for m in moves if m['species']==family['name']],key=lambda m:m['slot'])
        assert any(m['power'] for m in row)
        for d in family['nationalIds']:
            f=data['formStats'][d-1]
            assert f['species']==family['species']
            assert f['powers']==[(m['power']*f['powerPercent']+50)//100 for m in row]
    return data

def skill_manifest(roster):
    data = load_catalog()
    forms = list(roster)
    for batch in ['137-146','147-151']:
        forms += json.loads((ROOT/f'assets/pokemon/plan-{batch}.json').read_text())['items']
    form_names = {p['nationalId']:p['name'] for p in forms}
    by_name = {p['name']:p for p in roster if not p['stage']}
    families = {f['name']:f for f in data['families']}
    result = []
    for m in data['moves']:
        f = families[m['species']]
        active = m['species'] in by_name
        if active:
            icon = (f'effects/{["电","草","火","水"].index(m["type"])}-2.png'
                    if m['type'] in ['电','草','火','水'] else f'pets/{by_name[m["species"]]["id"]}-20.png')
        else:
            icon = f'../../assets/animation-templates/{f["nationalIds"][0]:03}/attack-00.png'
        result.append(dict(m, status='animated', icon=icon, familyId=f['species'],
                           nationalIds=f['nationalIds'], familyNames=[form_names[d] for d in f['nationalIds']], runtimeIntegrated=active,
                           formPowers=[dict(nationalId=d, power=data['formStats'][d-1]['powers'][m['slot']], percent=data['formStats'][d-1]['powerPercent']) for d in f['nationalIds']],
                           animation='reviewed pet frames + shared LVGL native particles'))
    return result

def write_core():
    data = load_catalog()
    q = lambda s: json.dumps(s, ensure_ascii=False)
    rows = ['#include "moves.h"', '/* Generated by tools/move_catalog.py. Old move IDs remain stable. */',
            'const pp_move pp_moves[PP_MOVE_CATALOG_COUNT] = {']
    for m in data['moves']:
        rows.append('  {'+', '.join([q(m['name']),q(m['type']),q(m['description']),'PP_'+TYPES[m['type']],str(m['power'])])+'},')
    rows += ['};', 'const char *const pp_move_family_names[PP_MOVE_FAMILY_COUNT] = {',
             '  '+', '.join(q(f['name']) for f in data['families']), '};',
             'static const unsigned short family_moves[PP_MOVE_FAMILY_COUNT][PP_MOVE_SLOTS] = {']
    for f in data['families']:
        ids = [next(m['id'] for m in data['moves'] if m['species']==f['name'] and m['slot']==slot) for slot in range(4)]
        rows.append('  {'+', '.join(map(str,ids))+'},')
    rows += ['};', 'const pp_move *pp_move_catalog_at(unsigned species, unsigned slot) {',
             '  if (species >= PP_MOVE_FAMILY_COUNT || slot >= PP_MOVE_SLOTS) return 0;',
             '  return &pp_moves[family_moves[species][slot]];', '}',
             'const pp_move *pp_move_at(unsigned species, unsigned slot) {',
             '  return species < PP_SPECIES ? pp_move_catalog_at(species, slot) : 0;', '}', '']
    rows += ['static const unsigned short form_power[151][4] = {']
    rows += ['  {'+', '.join(map(str,f['powers']))+'},' for f in data['formStats']]
    rows += ['};', 'unsigned pp_move_form_power(unsigned national_id, unsigned slot) {', '  return national_id>=1 && national_id<=151 && slot<4 ? form_power[national_id-1][slot] : 0;', '}']
    (ROOT/'core/moves.c').write_text('\n'.join(rows))

if __name__ == '__main__':
    write_core()
    print('Generated firmware catalog; playable species boundary unchanged')

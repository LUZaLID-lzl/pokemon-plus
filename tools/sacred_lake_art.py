# Exact native pixels on the exposed fork. Polygon interpolation had left
# diagonal gaps through the bark between the upper crown and S-shaped trunk.
FORK_EDGE_RUNS = [(43,71,3),(44,70,4),(45,70,3),(46,70,2),
                  (47,70,2),(48,70,2),(49,70,4),(50,73,2)]

def build_front(scene):
    image = scene.resize((120,120), Image.Resampling.NEAREST).convert('RGBA')
    mask = Image.new('L',(120,120))
    draw = ImageDraw.Draw(mask)
    for polygon in SILHOUETTES:
        draw.polygon(polygon, fill=255)
    for y,x,n in FORK_EDGE_RUNS:
        draw.line((x,y,x+n-1,y), fill=255)
    image.putalpha(mask)
    return image

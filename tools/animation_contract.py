"""Generate both LVGL targets' species-specific playback contract from JSON."""
def write_header(path, spec):
    count=spec.get('artCount',4)
    profiles=[spec['speciesOverrides'].get(str(i),spec) for i in range(count)]
    counts=[p['framesPerPet'] for p in profiles]
    offsets=[];total=0
    for n in counts:offsets.append(total);total+=n
    durations=[];once=[]
    for p in profiles:
        rows=[];mask=0
        for i,a in enumerate(spec['actions']):
            d=p.get('durationsMs',{}).get(a,[spec['frameMs']]*len(p['actions'][a]))
            rows.append('{'+', '.join(map(str,d+[0]*(8-len(d))))+'}')
            if p.get('modes',{}).get(a)=='one-shot':mask|=1<<i
        durations.append('  {'+', '.join(rows)+'}')
        once.append(mask)
    head=f'''#pragma once
#include <stdbool.h>
#include <stdint.h>
/* Generated by prepare_assets.py from assets/pet-animation.json. */
#define PP_ART_COUNT {count}
#define PP_SPRITE_SIZE 48
#define PP_FRAME_COUNT 48
#define PP_TOTAL_FRAMES {total}
#define PP_FRAME_MS 33
#define PP_POSE_IDLE 0
#define PP_POSE_WALK 4
#define PP_POSE_HAPPY 8
#define PP_POSE_EAT 12
#define PP_POSE_SLEEP 16
#define PP_POSE_ATTACK 20
static const uint16_t pp_frame_counts[PP_ART_COUNT] = {{{', '.join(map(str,counts))}}};
static const uint16_t pp_frame_offsets[PP_ART_COUNT] = {{{', '.join(map(str,offsets))}}};
static const uint8_t pp_once_masks[PP_ART_COUNT] = {{{', '.join(map(str,once))}}};
static const uint16_t pp_frame_durations[PP_ART_COUNT][6][8] = {{
'''+',\n'.join(durations)+'''\n};
static inline unsigned pp_pet_frame_count(unsigned art) { return pp_frame_counts[art]; }
static inline unsigned pp_pet_frame_offset(unsigned art) { return pp_frame_offsets[art]; }
/* Legacy pose constants map to the corresponding row for each art. */
static inline unsigned pp_animation_frame(unsigned art, unsigned pose, uint32_t elapsed) {
  if (art >= PP_ART_COUNT) art = 0;
  unsigned action=pose/4, count=pp_pet_frame_count(art)/6;
  if (action >= 6) action=0;
  unsigned total=0;
  for (unsigned i=0;i<count;i++) total+=pp_frame_durations[art][action][i];
  if ((pp_once_masks[art] & (1u<<action)) && elapsed>=total) return action*count+count-1;
  elapsed%=total;
  unsigned frame=0;
  while (frame<count-1 && elapsed>=pp_frame_durations[art][action][frame])
    elapsed-=pp_frame_durations[art][action][frame++];
  return action*count+frame;
}
typedef struct { uint32_t start; unsigned pose, art; bool initialized; } pp_animation_clock;
static inline unsigned pp_animation_update(pp_animation_clock *clock, unsigned art, unsigned pose, uint32_t now) {
  if (!clock->initialized || clock->pose!=pose || clock->art!=art) {
    clock->initialized=true; clock->pose=pose; clock->art=art; clock->start=now;
  }
  return pp_animation_frame(art,pose,now-clock->start);
}
'''
    path.write_text(head)

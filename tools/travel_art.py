"""Travel-only background catalog and offline image processing."""
from pathlib import Path
from PIL import Image, ImageEnhance, ImageFilter
import json

def load_catalog(root):
    catalog=json.loads((root/'assets/travel-backgrounds.json').read_text())
    assert [x['id'] for x in catalog['items']]==list(range(10))
    assert (catalog['width'],catalog['height'])==(360,112)
    assert all(len(x['activities'])==3 and len(x['encounters'])==2 for x in catalog['items'])
    return catalog

def write_header(root,catalog):
    q=lambda s:json.dumps(s,ensure_ascii=False)
    lines=['#pragma once','/* Generated by tools/prepare_travel.py from assets/travel-backgrounds.json. */',
           '#define PP_TRAVEL_DESTINATIONS 10','#define PP_TRAVEL_THEME_ENTRIES \\']
    for i,x in enumerate(catalog['items']):
        row='  {'+q(x['name'])+', {'+', '.join(map(q,x['activities']))+'}, {'+', '.join(map(q,x['encounters']))+'}}'
        lines.append(row+(', \\' if i<9 else ''))
    (root/'core/travel_catalog.h').write_text('\n'.join(lines)+'\n')

def background(root,item):
    im=Image.open(root/'assets'/item['source']).convert('RGB')
    # Crop to a panoramic 3:1 stage before native-grid conversion; never distort.
    w,h=im.size
    if w/h>3:
        width=h*3;im=im.crop(((w-width)//2,0,(w+width)//2,h))
    else:
        height=w//3;im=im.crop((0,(h-height)//2,w,(h+height)//2))
    im=im.resize((120,40),Image.Resampling.NEAREST).quantize(colors=48,dither=Image.Dither.NONE).convert('RGB')
    im=ImageEnhance.Contrast(im).enhance(0.84)
    im=im.resize((360,120),Image.Resampling.NEAREST).crop((0,4,360,116))
    im=im.filter(ImageFilter.GaussianBlur(radius=0.65)).quantize(colors=64,dither=Image.Dither.NONE).convert('RGB')
    # Keep the entire panorama. The LVGL screen / web preview clips the circle;
    # baking a dark round mask into a scrolling source would move it into view.
    return im

def export_travel(root,export):
    catalog=load_catalog(root);write_header(root,catalog)
    for item in catalog['items']:export(background(root,item),'travel-scenes',str(item['id']))
    return {'selection':catalog['selection'],'width':360,'height':112,
            'destinations':[{'id':x['id'],'name':x['name'],'image':f'travel-scenes/{x["id"]}.png'} for x in catalog['items']]}

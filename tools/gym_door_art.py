"""Place gym characters by opaque feet on measured dry floor, offline only."""
from PIL import Image, ImageDraw, ImageChops
import json


def _mask(polygons):
    mask=Image.new('L',(360,360))
    draw=ImageDraw.Draw(mask)
    for polygon in polygons:draw.polygon([tuple(p) for p in polygon],fill=255)
    return mask


def _fit(image,size):
    image=image.convert('RGBA')
    image=image.crop(image.getbbox())
    image.thumbnail(tuple(size),Image.Resampling.NEAREST)
    return image.crop(image.getbbox())


def build_gym_doors(root):
    folder=root/'assets/gyms'
    recipe=json.loads((folder/'door-team-slices.json').read_text())
    atlas=Image.open(root/recipe['source']).convert('RGBA')
    roster=json.loads((root/'assets/pet-roster.json').read_text())
    reports=[]
    for spec,origin in zip(recipe['gyms'],recipe['positions']):
        trainer_atlas=Image.open(root/spec['source']).convert('RGBA') if 'source' in spec else atlas
        trainer=trainer_atlas.crop(tuple(spec['box']))
        trainer.putalpha(trainer.getchannel('A').point(lambda a:255 if a>=recipe['alphaThreshold'] else 0))
        trainer=_fit(trainer,spec['trainer']['size'])
        trainer=trainer.quantize(colors=24,method=Image.Quantize.FASTOCTREE).convert('RGBA')
        trainer.putalpha(trainer.getchannel('A').point(lambda a:255 if a>=128 else 0))
        trainer=trainer.crop(trainer.getbbox())
        actors=[('leader',trainer,spec['trainer'])]
        for i,(art,placement) in enumerate(zip(spec['pets'],spec['petPlacements'])):
            pet=_fit(Image.open(root/'assets'/roster[art]['source']),placement['size'])
            actors.append((f'pet-{art}',pet,placement))
        group=Image.new('RGBA',tuple(recipe['size']))
        standing=_mask(spec['standingAreas']);ground=_mask(spec['groundAreas']);members=[]
        # Feet farther down the ground plane are drawn in front.
        for name,sprite,placement in sorted(actors,key=lambda a:a[2]['foot'][1]):
            fx,fy=placement['foot'];x=fx-sprite.width//2;y=fy-sprite.height
            assert origin[0]<=x and origin[1]<=y and x+sprite.width<=origin[0]+group.width and y+sprite.height<=origin[1]+group.height,(spec['gym'],name,'sprite clipped by group canvas')
            silhouette=Image.new('L',(360,360));silhouette.paste(sprite.getchannel('A'),(x,y))
            assert not ImageChops.subtract(silhouette,standing).getbbox(),(spec['gym'],name,'wall/water/railing overlap')
            # A small contact shadow is also constrained to the measured floor.
            rx=min(6,max(3,sprite.width//3))
            assert origin[0]<=fx-rx and fx+rx<origin[0]+group.width and origin[1]<=fy-1 and fy+1<origin[1]+group.height,(spec['gym'],name,'shadow clipped by group canvas')
            shadow=Image.new('L',(360,360));ImageDraw.Draw(shadow).ellipse((fx-rx,fy-1,fx+rx,fy+1),fill=255)
            assert not ImageChops.subtract(shadow,ground).getbbox(),(spec['gym'],name,'feet outside dry ground')
            ImageDraw.Draw(group).ellipse((fx-rx-origin[0],fy-1-origin[1],fx+rx-origin[0],fy+1-origin[1]),fill=(64,62,54,255))
            group.alpha_composite(sprite,(x-origin[0],y-origin[1]))
            members.append({'member':name,'foot':[fx,fy],'bounds':[x,y,x+sprite.width,y+sprite.height],'dryFloor':True,'noSceneryOverlap':True})
        assert group.getbbox() and set(group.getchannel('A').getdata())=={0,255}
        group.save(folder/f'door-team-{spec["gym"]}.png')
        reports.append({'gym':spec['gym'],'position':origin,'members':members})
    header='#pragma once\n#include <stdint.h>\n/* Generated by tools/gym_door_art.py; screen coordinates. */\n'
    header+=f'#define PP_GYM_DOOR_COUNT {len(recipe["positions"])}\n'
    header+='static const int16_t pp_gym_door_positions[PP_GYM_DOOR_COUNT][2] = {'+','.join('{'+','.join(map(str,p))+'}' for p in recipe['positions'])+'};\n'
    (root/'main/gym_door_layout.h').write_text(header)
    (root/'build/gym-door-ground-layout.json').write_text(json.dumps(reports,ensure_ascii=False,indent=2)+'\n')
    return recipe


if __name__=='__main__':
    from pathlib import Path
    build_gym_doors(Path(__file__).resolve().parents[1])

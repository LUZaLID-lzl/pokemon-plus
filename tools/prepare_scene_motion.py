"""Build small native-pixel feature masks; no new runtime images or frame banks."""
from pathlib import Path
from sacred_lake_art import build_front
from PIL import Image, ImageDraw, ImageFilter
import json
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'assets/scene-motion.json'
config=json.loads(source.read_text()); scenes=[];features=[];runs=[]
from scene_materials import selected
from scene_nest_art import catalog as nest_catalog
nests=nest_catalog()
kinds=['canopy','water','crystal','glow','stars','cloud']
for i,recipe in enumerate(config['scenes']):
 im=Image.open(ROOT/f'sdcard/pokemon-plus/scenes/{i}.png').convert('RGB').resize((120,120),Image.Resampling.NEAREST)
 sf=[]
 for f in recipe:
  mask=Image.new('L',(120,120));ImageDraw.Draw(mask).polygon(f['polygon'],fill=255)
  for y in range(120):
   for x in range(120):
    # Whole3px block must be in visible circle and outside text/buttons.
    safe=all((px-179.5)**2+(py-179.5)**2<171**2 and not(80<=px<280 and 22<=py<112) and not(98<=px<262 and 258<=py<328) for px in (3*x,3*x+2) for py in (3*y,3*y+2))
    if not safe or not selected(f['gate'],*im.getpixel((x,y))):mask.putpixel((x,y),0)
  if f['kind']=='canopy':
   closed=mask.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3))
   for y in range(1,119):
    for x in range(1,119):
     if mask.getpixel((x-1,y)) and mask.getpixel((x+1,y)) and closed.getpixel((x,y)):mask.putpixel((x,y),255)
  # Pin shorelines/fall banks. Canopy destination safety is checked at runtime.
  if f['kind']=='water':mask=mask.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3)).filter(ImageFilter.MinFilter(3))
  if i==12:
   alpha=build_front(im).getchannel('A')
   for yy in range(120):
    for xx in range(120):
     # Same blue palette, different materials: never flow bark or sway mountains.
     foreground=bool(alpha.getpixel((xx,yy)))
     if (f['kind']=='canopy' and not foreground) or (f['kind']=='water' and foreground):
      mask.putpixel((xx,yy),0)
  # Egg cradles stay firmly on the ground, even when foliage/water sways.
  nx,ny=nests['scenes'][i]['position'];nw,nh=nests['size']
  ImageDraw.Draw(mask).rectangle((nx//3,ny//3,(nx+nw-1)//3,(ny+nh-1)//3),fill=0)
  if nests.get('embeddedSources'):
   # Root/snow/sand supports now extend into the edited ground around the
   # cradle. Keep that physical support fixed as well as the woven rim.
   ImageDraw.Draw(mask).rectangle((nx//3-4,ny//3-4,nx//3+27,ny//3+18),fill=0)
  rr=[]
  for y in range(120):
   x=0
   while x<120:
    if not mask.getpixel((x,y)):x+=1;continue
    a=x
    while x<120 and mask.getpixel((x,y)):x+=1
    rr.append([y,a,x-a])
  if not rr:continue
  feat={k:f[k] for k in ('kind','period','phase')};feat['y0']=min(r[0] for r in rr);feat['y1']=max(r[0] for r in rr);feat['runs']=rr;sf.append(feat)
  features.append((kinds.index(f['kind']),f['period'],f['phase'],feat['y0'],feat['y1'],len(runs),len(rr)));runs+=rr
 scenes.append(sf)
(ROOT/'web/scene-motion.json').write_text(json.dumps({'tickMs':config['tickMs'],'scenes':scenes},separators=(',',':'))+'\n')
lines=['/* Generated by tools/prepare_scene_motion.py;120px masks from existing art. */','static const pp_scene_run motion_runs[] = {']
lines += [' {%d,%d,%d},'%tuple(r) for r in runs];lines += ['};','static const pp_scene_feature motion_features[] = {']
lines += [' {%d,%d,%d,%d,%d,%d,%d},'%f for f in features];lines += ['};','static const pp_scene_range motion_scenes[] = {'];at=0
for s in scenes:lines+=[' {%d,%d},'%(at,len(s))];at+=len(s)
lines+=['};'];(ROOT/'core/scene_motion_config.h').write_text('\n'.join(lines)+'\n')
print(f'{len(features)} anchored features / {len(runs)} mask spans; {len(runs)*3+len(features)*16} bytes approx')

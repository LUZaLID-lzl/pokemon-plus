"""Solid, bevelled pixel arrows shared by native and Web battle HUDs."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
# Outline, upper edge, body, lower edge. Match the mint pixel navigation style.
PALETTES=[
 [0x102c3c,0xb8d1d6,0x7896a0,0x486873],
 [0x102c3c,0xd6f8d9,0x82d7a7,0x408b6b],
 [0x102c3c,0xffe1a3,0xe7b769,0x9c703b],
 [0x102c3c,0xffd2d8,0xeb92a5,0xa85370]]
def spans(kind):
 shape=set()
 def shaft(a,b):
  for x in range(a,b+1):
   for y in range(2,5):shape.add((x,y))
 def head(tip):
  for d in range(4):
   for y in range(3-d,4+d):shape.add((tip-d,y))
 if kind==0:shaft(3,64);head(68)
 elif kind==1:shaft(3,56);head(60);head(68)
 elif kind==2:
  for x in range(9,57,9):shaft(x,x+4)
  head(63)
 else:
  shaft(3,40);head(44)
  # Broad top and tapered point make a shield, rather than a text-like bar.
  for y,(a,b) in enumerate([(58,64),(58,64),(58,64),(58,64),(59,63),(60,62),(61,61)]):
   for x in range(a,b+1):shape.add((x,y))
 pixels={}
 for x,y in shape:
  for dx in [-1,0,1]:
   for dy in [-1,0,1]:pixels[(x+dx,y+dy)]=0
 for x,y in shape:pixels[(x,y)]=1 if (x,y-1) not in shape else 3 if (x,y+1) not in shape else 2
 # Single-pixel sheen in the shield keeps its interior clear at 1x resolution.
 if kind==3:
  for xy in [(60,2),(60,3),(61,4)]:pixels[xy]=1
 out=[]
 for y in range(-1,8):
  x=0
  while x<72:
   if (x,y) not in pixels:x+=1;continue
   color=pixels[(x,y)];start=x
   while x<72 and pixels.get((x,y))==color:x+=1
   out.append([start,y+1,x-start,color])
 return out
SPANS=[spans(k) for k in range(4)]
def generate():
 count=max(map(len,SPANS));h='/* Generated by tools/battle_relation.py. Solid shaded pixel glyphs. */\n#pragma once\n'
 h+='typedef void (*pp_relation_pixel)(int,int,unsigned,unsigned,unsigned,void *);\n'
 h+='static const uint8_t pp_relation_spans[4][%d][4]={'%count+','.join('{'+','.join('{'+','.join(map(str,s))+'}' for s in kind)+'}' for kind in SPANS)+'};\n'
 h+='static const unsigned pp_relation_colors[4][4]={'+','.join('{'+','.join(hex(c) for c in row)+'}' for row in PALETTES)+'};\n'
 h+='''static inline unsigned pp_relation_kind(unsigned factor,unsigned power){
 return !power||factor==100?0:!factor?3:factor>100?1:2;
}
static inline void pp_relation_paint(unsigned side,unsigned kind,unsigned opacity,pp_relation_pixel paint,void *user){
 for(unsigned i=0;i<sizeof(pp_relation_spans[0])/sizeof(pp_relation_spans[0][0]);i++){
  const uint8_t *s=pp_relation_spans[kind][i];if(!s[2])break;
  paint(side?72-s[0]-s[2]:s[0],s[1]+(side?10:0),s[2],pp_relation_colors[kind][s[3]],opacity,user);
 }
}
'''
 (ROOT/'main/battle_relation.h').write_text(h)
 js='// Generated by tools/battle_relation.py; solid, outlined, bevelled pixel arrows.\n'
 js+='const spans='+json.dumps(SPANS,separators=(',',':'))+';\nconst palettes='+json.dumps([['#%06x'%c for c in row] for row in PALETTES])+';\n'
 js+='''export const relationKind=(factor,power)=>!power||factor===100?0:!factor?3:factor>100?1:2;
export function paintBattleRelation(side,kind,opacity,paint){
 for(const [start,row,width,color] of spans[kind])paint(side?72-start-width:start,row+(side?10:0),width,palettes[kind][color],opacity);
}
'''
 (ROOT/'web/battle-relation-pixels.mjs').write_text(js)
if __name__=='__main__':generate();print('Generated solid 3px shafts, filled heads, outline/bevel and shield; shared72x19 HUD')
